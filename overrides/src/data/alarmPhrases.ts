function tokens(value: string): string[] {
  return (value.toLowerCase().match(/[a-z]+(?:-[a-z]+)*/g) || [])
    .flatMap((word) => word.split('-'));
}

function sequenceStart(source: string[], candidate: string[]): number {
  return source.findIndex((_, start) =>
    candidate.every((word, offset) => source[start + offset] === word),
  );
}

export function getAlarmPhraseCards(entry: AlarmSummaryEntry): AlarmPhraseCard[] {
  const alarmTokens = tokens(entry.alarm);
  const matches = Object.entries(ALARM_PHRASE_CHINESE)
    .map(([text, chinese]) => ({
      text,
      chinese,
      fullAlarm: false,
      start: sequenceStart(alarmTokens, tokens(text)),
      length: tokens(text).length,
    }))
    .filter((card) => card.start >= 0 && card.length < alarmTokens.length)
    .sort((a, b) => a.start - b.start || b.length - a.length)
    .map(({ start: _start, length: _length, ...card }) => card);

  return [
    {
      text: entry.alarm,
      chinese: ALARM_CHINESE[entry.id],
      fullAlarm: true,
    },
    ...matches,
  ];
}
